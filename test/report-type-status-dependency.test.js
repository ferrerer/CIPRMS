// test/report-type-status-dependency.test.js
//
// Covers all 12 requirements from the 2026-10-05 "Report Type and Status Field
// Dependency" feature request:
//   1.  Summary enables Status selection (backend: user-supplied status respected)
//   2.  Active disables Status selection (backend: implied status is authoritative)
//   3.  Expired disables Status selection
//   4.  Inactive disables Status selection
//   5.  Expiring Soon disables Status selection
//   6.  Switching back to Summary re-enables Status selection (status filter works)
//   7.  Stale status value cannot create conflicting report results
//   8.  Comparison fields follow the same rules independently
//   9.  Mid-Year Report and Yearly Output Report absent from Comparison Report Type
//  10.  Primary Report Type options unchanged
//  11.  Report generation uses correct filters (comparison result correctness)
//  12.  Existing date/country/grouping/export filters still work

const fs      = require('fs');
const path    = require('path');
const request = require('supertest');
const app     = require('../cirl');
const { connectDB, closeDB } = require('../db');
const { createTestUser, loginAs, cleanupAll } = require('./helpers');

// ─── helpers ──────────────────────────────────────────────────────────────────
const read = (...p) => fs.readFileSync(path.join(__dirname, '..', ...p), 'utf8');
const view = read('views', 'administrator', 'reports.ejs');
const fmt  = (d) => d.toLocaleDateString('en-US', { month: 'short', day: 'numeric', year: 'numeric' });
const days = (n) => { const d = new Date(); d.setDate(d.getDate() + n); return d; };

// ─── static (view-file) tests ─────────────────────────────────────────────────
